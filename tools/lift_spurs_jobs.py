"""Lift SPURS jobchain job binaries dumped by the runtime and register them by fingerprint.

The runtime writes each job it cannot dispatch to SPU_DUMP_MISS=<dir> as
spujob_<FNV1a64>_<size>.bin. A job binary is position independent and the
runtime stages it at LS 0 (runtime/spu/spurs_job.c), so each one is lifted at
base 0 with entry 0 and registered under the same fingerprint the dispatcher
computes over the raw bytes.

Usage: python tools/lift_spurs_jobs.py --jobs <dir> --out <spu dir> [--prefix naruto]
Writes <out>/<job>/spu_recomp.{c,h} and <out>/spurs_jobs_register.c."""
import argparse
import glob
import os
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
TOOLS = os.path.join(ROOT, 'external', 'ps3recomp', 'tools')

IMAGE_BASE = 300  # clear of the ELF images (0..), jobmods (200..) and the policy (100)


def fnv1a64(b):
    h = 1469598103934665603
    for x in b:
        h = ((h ^ x) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--jobs', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--prefix', default='port')
    ap.add_argument('--sdk', default=os.path.join(ROOT, 'external', 'ps3recomp'))
    args = ap.parse_args()
    tools = os.path.join(os.path.abspath(args.sdk), 'tools')
    sys.path.insert(0, tools)
    from wrap_spu_elf import wrap
    from lift_jobmods import manual_link_targets, switch_table_targets

    jobs = sorted(glob.glob(os.path.join(args.jobs, 'spujob_*.bin')))
    if not jobs:
        sys.exit(f'no spujob_*.bin in {args.jobs} -- run the game with SPU_DUMP_MISS first')
    os.makedirs(args.out, exist_ok=True)
    tmp = os.path.join(args.out, '_job.elf')
    lifted = []
    for path in jobs:
        raw = open(path, 'rb').read()
        name = os.path.splitext(os.path.basename(path))[0]
        fp = fnv1a64(raw)
        if f'{fp:016X}' not in name:
            print(f'  skip {name}: fingerprint 0x{fp:016X} does not match its name', file=sys.stderr)
            continue
        with open(tmp, 'wb') as f:
            f.write(wrap(raw, base=0, entry=0))
        extra = [0] + manual_link_targets(raw, base=0) + switch_table_targets(raw, base=0)
        cmd = [sys.executable, os.path.join(tools, 'spu_lifter.py'), '--auto-functions', tmp,
               '--base', '0', '--symbol-prefix', f'{name}_', '-o', os.path.join(args.out, name),
               '--source-name', 'spu_recomp.c', '--header-name', 'spu_recomp.h',
               '--extra-funcs', ','.join(hex(a) for a in sorted(set(extra)))]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            print(f'  FAIL {name}\n{r.stderr}', file=sys.stderr)
            sys.exit('SPURS job generation failed; see the diagnostic above')
        unsup = next((ln.split()[0] for ln in r.stdout.splitlines() if 'unsupported instruction' in ln), '0')
        print(f'  {name}: fp=0x{fp:016X} size={len(raw)} unsupported={unsup}')
        lifted.append((name, fp))
    if os.path.exists(tmp):
        os.remove(tmp)

    lines = ['/* spurs_jobs_register.c -- GENERATED by tools/lift_spurs_jobs.py. */',
             '#include <stdint.h>', '',
             'struct spu_context;',
             'extern void spu_begin_image(int image_id);',
             'extern void spu_workload_register_img(uint64_t fp, void (*fn)(struct spu_context*),',
             '                                      int image_id, const char* name);', '']
    for name, _ in lifted:
        lines += [f'extern void {name}_spu_func_00000000(struct spu_context*);',
                  f'extern void {name}_spu_recomp_register(void);']
    lines += ['', f'void {args.prefix}_spurs_jobs_register_all(void)', '{']
    for i, (name, fp) in enumerate(lifted):
        img = IMAGE_BASE + i
        lines += [f'    spu_begin_image({img}); {name}_spu_recomp_register();',
                  f'    spu_workload_register_img(0x{fp:016X}ULL, {name}_spu_func_00000000, {img}, "{name}");']
    lines += ['    spu_begin_image(0);', '}', '',
              f'__attribute__((constructor)) static void {args.prefix}_spurs_jobs_ctor(void)',
              '{', f'    {args.prefix}_spurs_jobs_register_all();', '}', '']
    reg = os.path.join(args.out, 'spurs_jobs_register.c')
    with open(reg, 'w') as f:
        f.write('\n'.join(lines))
    print(f'Wrote {reg} ({len(lifted)} job(s))')


if __name__ == '__main__':
    main()
